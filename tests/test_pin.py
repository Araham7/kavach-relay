from playwright.sync_api import sync_playwright
def log(*a): print(*a, flush=True)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path="/usr/bin/google-chrome")
    ctx=b.new_context(viewport={"width":1100,"height":800},bypass_csp=True,permissions=["clipboard-read","clipboard-write"]); pg=ctx.new_page()
    pg.on("pageerror",lambda e:log("ERR",e))
    pg.goto("http://localhost:8099/?test=1"); pg.wait_for_timeout(500)
    pg.fill("#pin","111111"); pg.fill("#pin2","111111"); pg.click("#pinBtn")
    pg.wait_for_selector("text=Your recovery key"); code=pg.inner_text(".reccode"); log("recovery code:",code)
    pg.screenshot(path="/tmp/rec.png")
    pg.click("#recOk")
    pg.evaluate("window.__kv.ST.set.theme='dracula'")
    # change pin wrong old
    pg.click("#setBtn"); pg.click("[data-tab='security']"); pg.click("#chPin"); pg.fill("#op","999999"); pg.fill("#np1","222222"); pg.fill("#np2","222222"); pg.click("#npOk"); pg.wait_for_timeout(1500); log("wrong-old toast:",pg.inner_text("#toast"))
    pg.fill("#op","111111"); pg.click("#npOk"); pg.wait_for_timeout(1800); log("change toast:",pg.inner_text("#toast"))
    pg.click("#lockBtn"); pg.wait_for_selector("#lock:not(.hidden)")
    pg.fill("#pin","111111"); pg.click("#pinBtn"); pg.wait_for_timeout(1200); log("old pin now:",pg.inner_text("#lockHint"))
    pg.fill("#pin","222222"); pg.click("#pinBtn"); pg.wait_for_selector("#app:not(.hidden)"); log("new pin unlock OK, theme:",pg.evaluate("window.__kv.ST.set.theme"))
    pg.click("#lockBtn"); pg.wait_for_selector("#lock:not(.hidden)")
    pg.click("#forgotBtn"); log("mode:",pg.evaluate("window.__kv.mode"))
    pg.fill("#rec","AAAA-BBBB-CCCC-DDDD-EEEE-FFFF"); pg.fill("#pin","333333"); pg.fill("#pin2","333333"); pg.click("#pinBtn"); pg.wait_for_timeout(2000); log("bad recovery:",pg.inner_text("#lockHint"))
    pg.fill("#rec",code.lower().replace("-"," ")); pg.fill("#pin","333333"); pg.fill("#pin2","333333"); pg.click("#pinBtn")
    pg.wait_for_selector("#app:not(.hidden)"); log("recovered, theme:",pg.evaluate("window.__kv.ST.set.theme"))
    pg.click("#lockBtn"); pg.fill("#pin","333333"); pg.click("#pinBtn"); pg.wait_for_selector("#app:not(.hidden)"); log("unlock with reset PIN OK")
    pg.click("#setBtn"); pg.click("[data-tab='security']"); pg.click("#newRec"); pg.fill("#rp","333333"); pg.click("#rpOk"); pg.wait_for_selector("text=New recovery key"); log("new code:", pg.inner_text(".reccode")!=code)
    pg.click("#recOk"); pg.click("#lockBtn"); pg.click("#forgotBtn"); pg.fill("#rec",code); pg.fill("#pin","444444"); pg.fill("#pin2","444444"); pg.click("#pinBtn"); pg.wait_for_timeout(2500); log("old recovery after rotate:",pg.inner_text("#lockHint"))
    pg.click("#forgotBtn"); pg.screenshot(path="/tmp/lock.png")
    b.close()
